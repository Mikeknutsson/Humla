-- Reclassify existing credits once at the shared reporting boundary.
-- Source records, row identity and result are unchanged. Applies to future generations.
-- Supplier credit invoices and other cost centers keep their existing classification.
CREATE OR REPLACE VIEW private.hub_kpi_report_facts_v1 AS SELECT f.generation_id,
f.tenant_id,
f.fiscal_year,
f.fact_id,
f.occurred_on,
CASE WHEN credit THEN 'revenue' ELSE f.kind END AS kind,
CASE WHEN credit THEN -f.amount ELSE f.amount END AS amount,
CASE WHEN credit THEN 'internal_workshop' ELSE f.category END AS category,
f.project,
f.vehicle,
f.unit_id,
f.unit_name,
f.business_group,
f.source,
f.description,
f.account,
f.file_name,
f.row_number,
CASE WHEN credit THEN coalesce(f.original,'{}'::jsonb) || jsonb_build_object('_humla_internal_workshop_credit',jsonb_build_object('basis','NEXT account 4630, Kreditering Intern AO, KST 40','original_kind','cost','original_amount',f.amount,'internal',true)) ELSE f.original END AS original,
f.cost_center,
f.cost_center_name,
f.classification_source,
CASE WHEN credit THEN coalesce(f.display_original,'{}'::jsonb) || jsonb_build_object('_humla_internal_workshop_credit',jsonb_build_object('basis','NEXT account 4630, Kreditering Intern AO, KST 40','original_kind','cost','original_amount',f.amount,'internal',true)) ELSE f.display_original END AS display_original FROM private.hub_kpi_prepared_facts f CROSS JOIN LATERAL (SELECT (f.cost_center='40' AND f.source='NEXT' AND f.kind='cost' AND f.amount<0 AND f.account='4630' AND f.description ILIKE 'Kreditering Intern AO%') AS credit) c WHERE NOT COALESCE((f.display_original->>'_humla_excluded_from_kpi')::boolean,false);
CREATE OR REPLACE VIEW private.hub_kpi_report_display_facts_v1 AS SELECT d.generation_id,
d.tenant_id,
d.fiscal_year,
d.fact_id,
d.occurred_on,
CASE WHEN c.fact_id IS NOT NULL THEN 'revenue' ELSE d.kind END AS kind,
CASE WHEN c.fact_id IS NOT NULL THEN -d.amount ELSE d.amount END AS amount,
CASE WHEN c.fact_id IS NOT NULL THEN 'internal_workshop' ELSE d.category END AS category,
d.project,
d.vehicle,
d.unit_id,
d.unit_name,
d.business_group,
d.source,
d.cost_center,
CASE WHEN c.fact_id IS NOT NULL THEN coalesce(d.original,'{}'::jsonb) || jsonb_build_object('_humla_internal_workshop_credit',jsonb_build_object('basis','NEXT account 4630, Kreditering Intern AO, KST 40','original_kind','cost','original_amount',d.amount,'internal',true)) ELSE d.original END AS original FROM private.hub_kpi_prepared_display_facts d LEFT JOIN (SELECT f.generation_id,f.tenant_id,f.fact_id FROM private.hub_kpi_prepared_facts f WHERE f.cost_center='40' AND f.source='NEXT' AND f.kind='cost' AND f.amount<0 AND f.account='4630' AND f.description ILIKE 'Kreditering Intern AO%') c ON c.generation_id=d.generation_id AND c.tenant_id=d.tenant_id AND c.fact_id=d.fact_id AND d.cost_center='40' AND d.kind='cost' AND d.amount<0 AND d.source='NEXT' WHERE NOT COALESCE((d.original->>'_humla_excluded_from_kpi')::boolean,false);