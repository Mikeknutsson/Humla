import assert from 'node:assert/strict';
import {resolveForemanPeriod,foremanPeriodQuery} from '../src/lib/kpi/foreman-period.ts';
const today={year:2026,month:10,day:29};
const period=(q={},cutoff='2026-10-26',now=today)=>resolveForemanPeriod(q,cutoff,now);
assert.deepEqual([period().mode,period().from,period().to],['ytd','2026-09-01','2026-10-29']);
assert.equal(period({from:'2025-09-01',to:'2026-08-31'}).mode,'ytd','legacy date cookies must not replace default YTD');
assert.equal(period({period_mode:'revenue'}).to,'2026-10-26');
assert.equal(period({period_mode:'revenue'},null).to,null,'missing import data must not silently use today');
assert.equal(period({period_mode:'year'}).to,'2027-08-31');
assert.deepEqual([period({period_mode:'month',month:'1'}).from,period({period_mode:'month',month:'1'}).to],['2027-01-01','2027-01-31']);
assert.equal(period({period_mode:'month',month:'2',fiscal_year:'2023'},null,{year:2024,month:2,day:29}).to,'2024-02-29');
assert.equal(period({period_mode:'ytd',fiscal_year:'2022'},null,{year:2024,month:2,day:29}).to,'2023-02-28');
assert.throws(()=>period({month:'13'}));
assert.throws(()=>period({period_mode:'something'}));
assert.throws(()=>period({fiscal_year:'no'}));
assert.throws(()=>period({fiscal_year:'2027'}));
assert.throws(()=>period({},'2026-02-30'));
assert.equal(foremanPeriodQuery(period({period_mode:'month',month:'10'}),'selected-user').get('user_id'),'selected-user');
assert.equal(foremanPeriodQuery(period({period_mode:'month',month:'10'})).get('month'),'10');
assert.equal(foremanPeriodQuery(period()).has('month'),false);
console.log('PASS: YTD default, stale-cookie handling, import cutoff, missing data, fiscal boundaries, leap years, validation and preserved profile');
