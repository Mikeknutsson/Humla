import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import Module,{createRequire} from 'node:module';
import ts from 'typescript';
const require=createRequire(import.meta.url);
const React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
function compiled(file,overrides={}){
 const filename=path.resolve(file),m=new Module(filename);
 m.filename=filename;m.paths=Module._nodeModulePaths(path.dirname(filename));
 const normal=m.require.bind(m);
 m.require=id=>id in overrides?overrides[id]:normal(id);
 const output=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}}).outputText;
 m._compile(output,filename);return m.exports;
}
const helper=compiled('src/lib/kpi/foreman-trend.ts');
const styles=new Proxy({},{get:(_,key)=>String(key)});
const {ForemanResultTrend}=compiled('src/app/_components/foreman-result-trend.tsx',{'@/lib/kpi/foreman-trend':helper,'./foreman-result-trend.module.css':styles});
const point={date:'2026-10-29',revenue:1000,cost:700,result:300,margin_percent:30,target_result:200,target_margin_percent:20,deviation_amount:100,missing_targets:0};
const trend={from:'2026-09-01',to:'2026-10-29',generation:'test',area_target_margin_percent:20,points:[point],latest:point};
const render=t=>renderToStaticMarkup(React.createElement(ForemanResultTrend,{trend:t}));
let html=render(trend);
assert.match(html,/Resultatets utveckling/);
assert.match(html,/Mål för hela området/);
assert.match(html,/över.*mål/);
assert.match(html,/Resultat %/);
assert.match(html,/type="range"/);
assert.match(html,/Följ resultatet datum för datum/);
assert.match(html,/Visa siffror per datum/);
assert.match(html,/Mållinjen visar 20 % av hela områdets intäkter/);
assert.ok(!/NaN|Infinity/.test(html));
const missing={...point,target_result:null,target_margin_percent:null,deviation_amount:null,missing_targets:1};
html=render({...trend,area_target_margin_percent:null,points:[missing],latest:missing});
assert.match(html,/Områdets mål är inte komplett/);
assert.ok(!html.includes('Mål för hela området'),'missing target must not render a misleading goal legend');
html=render({...trend,points:[],latest:null});
assert.match(html,/Underlag saknas för perioden/);
assert.ok(!html.includes('<svg'),'no fake zero chart for missing data');
console.log('PASS: actual React component renders area goal, signed status, Resultat %, accessible controls and data table; missing goals and empty periods stay explicit');
