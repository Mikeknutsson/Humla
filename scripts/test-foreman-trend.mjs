import assert from 'node:assert/strict';
import {foremanTrendPlot} from '../src/lib/kpi/foreman-trend.ts';
const p=(date,result,target_result=null)=>({date,revenue:100,cost:100-result,result,margin_percent:result,target_result,target_margin_percent:target_result,deviation_amount:target_result==null?null:result-target_result,missing_targets:target_result==null?1:0});
const trend=(points,to='2026-10-31')=>({from:'2026-10-01',to,generation:'test',points,latest:points.at(-1)??null});
let input=trend([p('2026-10-01',-100,10),p('2026-10-29',50,20)]);
let plot=foremanTrendPlot(input);
assert.equal(plot.showTarget,true);
assert.ok(plot.y(-100)>plot.zero,'negative results must plot below zero');
assert.ok(plot.y(50)<plot.zero,'positive results must plot above zero');
assert.ok(plot.x('2026-10-29')<856,'do not extrapolate actuals into missing future days');
assert.ok(plot.target.startsWith('M64.00,'+plot.zero.toFixed(2)),'target starts at the zero baseline');
assert.ok(plot.min<-100&&plot.max>50,'both paths and zero remain within the scale');
assert.ok(!/NaN|Infinity/.test(plot.actual+plot.target+plot.area));
assert.equal(input.points[0].result,-100,'presentation must not mutate backend data');
plot=foremanTrendPlot(trend([p('2026-10-01',0),p('2026-10-29',0)]));
assert.equal(plot.showTarget,false);
assert.equal(plot.target,'','missing target must never draw a zero target line');
assert.ok(!/NaN|Infinity/.test(plot.actual+plot.area),'all-zero data remains renderable');
plot=foremanTrendPlot(trend([p('2026-10-01',50,10),p('2026-10-29',50,null)]));
assert.equal(plot.target,'','partial target coverage hides the entire goal line');
plot=foremanTrendPlot(trend([p('2026-10-01',100,10)],'2026-10-01'));
assert.ok(!/NaN|Infinity/.test(plot.actual+plot.target),'single-day selection works');
plot=foremanTrendPlot(trend([]));
assert.equal(plot.showTarget,false);
assert.ok(Number.isFinite(plot.zero));
console.log('PASS: signed result scale, full-period dates, no extrapolation, missing/partial goals, zero data, one day, empty data and immutable backend values');
